// Build rules/isone-2026.json from the per-domain sources in rules/isone-2026/*.json (S2b).
// Provenance: Claude Opus 5.5 · one-studio/design (T3, S2b) · 2026-10-06 · sign-off pending · v1
// One writer per domain file (S3 interconnection, S4 capacity_pfp + recs, S5 tax, S6 large_load); the merged
// file is GENERATED — never edit it by hand. Order of top-level keys is fixed so the output is stable.
//   node rules/build.mjs          write the merged file
//   node rules/build.mjs --check  exit 1 if the merged file differs from the sources
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.join(HERE, 'isone-2026');
const OUT = path.join(HERE, 'isone-2026.json');
const ORDER = ['_meta', 'interconnection', 'capacity_pfp', 'recs', 'tax', 'defaults', 'large_load'];

export function build() {
  const merged = {};
  const seen = new Set();
  for (const f of ORDER) {
    const part = JSON.parse(readFileSync(path.join(SRC, `${f}.json`), 'utf8'));
    for (const [k, v] of Object.entries(part)) {
      if (seen.has(k)) throw new Error(`rules key "${k}" defined twice (second time in ${f}.json)`);
      seen.add(k); merged[k] = v;
    }
  }
  merged._generated = 'GENERATED by rules/build.mjs from rules/isone-2026/*.json. Do not edit; edit the domain file and rebuild.';
  return JSON.stringify(merged, null, 1) + '\n';
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = build();
  if (process.argv.includes('--check')) {
    const same = readFileSync(OUT, 'utf8') === text;
    console.log(same ? 'rules up to date' : 'rules/isone-2026.json differs from rules/isone-2026/*.json: run node rules/build.mjs');
    process.exit(same ? 0 : 1);
  }
  writeFileSync(OUT, text);
  console.log(`built ${OUT}`);
}
